package switch_statement;

public class Switch_integers {

	public static void main(String[] args) {

		int a = 10;

		switch (a) {

		case 2:
			System.out.println("case 1 : even number");
			break;
		case 4:
			System.out.println("case 2 : even number");
			break;
		case 6:
			System.out.println("case 3 : even number");
			break;
		case 8:
			System.out.println("case 4 : even number");
			break;
		case 10:
			System.out.println("case 5 : even number");
			break;

		default:
			System.out.println("invalid number");
			break;
			
			
			
		

		}
	}

}
