package operators;

public class comparison_operator {

	public static void main(String[] args) {
		//> , < , >= , =< , == equal to , != not equal to 
		int a = 5;
		int b = 7; 
		boolean c=a>b;
		System.out.println(c);
				
		boolean f=a<b;
		System.out.println(f);
		
		boolean g=a>=b;
		System.out.println(g);
		
		boolean l=a<=b;
		System.out.println(l);
		
		boolean n=a!=b;
		System.out.println(n);
	} 


}

