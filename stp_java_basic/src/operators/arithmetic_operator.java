package operators;

public class arithmetic_operator {

	public static void main(String[] args) {

		// add
		int a = 8;
		int b = 5;
		System.out.println(a + b);

		// sub
		byte b1 = 30;
		byte c = 20;
		System.out.println(b1 - c);

		// division
		// quotient----/
		// remainder---%

		int r = 8;
		int n = 4;
		System.out.println("quotient will be as:" + r / n);
		System.out.println("remainder" + r % n);

		int f = 9;
		int k = 3;
		System.out.println("quotient will be as:" + f / k);
		System.out.println("remainder" + f % k);

		// multiplication

		int t = 5;
		int i = 4;
		System.out.println("multiplication" + t * i);

		int s = 8;
		System.out.println(++s);

		int y = 8;
		System.out.println(--y);

		// assignment
		int u = 9;
		int g = u + 4;
		System.out.println(g);

	}

}
